// Writes web/app-links.js (what the browser needs) from data/world/app-links.json (the source of truth).
//   node scripts/build-app-links.mjs
import { readFileSync, writeFileSync } from "node:fs";
const ROOT = new URL("..", import.meta.url).pathname;
const data = JSON.parse(readFileSync(ROOT + "data/world/app-links.json", "utf8"));
const out = {};
for (const [name, v] of Object.entries(data.apps)) {
  if (!v.site && !v.googlePlay && !v.appStore) continue;
  out[name.toLowerCase()] = { site: v.site, googlePlay: v.googlePlay, appStore: v.appStore };
}
writeFileSync(
  ROOT + "web/app-links.js",
  `// Generated by scripts/build-app-links.mjs from data/world/app-links.json. Do not edit.\n// Where to get an app: its site and its Google Play and App Store pages (collected ${data.source.retrieved || "n/a"}).\nexport const APP_LINKS = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`web/app-links.js: ${Object.keys(out).length} apps`);
