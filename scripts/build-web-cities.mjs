// Writes web/world-cities.json (what the browser needs to name the city a traveler is in) from data/world/cities.json.
//   node scripts/build-web-cities.mjs
import { readFileSync, writeFileSync } from "node:fs";
const ROOT = new URL("..", import.meta.url).pathname;
const { cities } = JSON.parse(readFileSync(ROOT + "data/world/cities.json", "utf8"));
const rows = cities.map((c) => [c.name.en, c.name.es, c.iso, Math.round(c.lat * 1000) / 1000, Math.round(c.lon * 1000) / 1000, c.id]);
writeFileSync(ROOT + "web/world-cities.json", JSON.stringify({ note: "Generated by scripts/build-web-cities.mjs. [name en, name es, ISO country, lat, lon, Wikidata id]. Wikidata, CC0.", cities: rows }) + "\n");
console.log(`web/world-cities.json: ${rows.length} cities`);
